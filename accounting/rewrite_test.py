import sys, csv, re, numpy as np
from collections import defaultdict
from sklearn.ensemble import GradientBoostingClassifier
from sklearn.model_selection import cross_val_predict, StratifiedKFold
from sklearn.metrics import roc_auc_score
def P(*a): print(*a); sys.stdout.flush()
SC="../work"
z=np.load(f"{SC}/deepfeats.npz",allow_pickle=True); z2=np.load(f"{SC}/resid2.npz")
I,J,y7,y8,base,katz,neurons=z['I'],z['J'],z['y7'],z['y8'],z['base'],z['katz'],list(z['neurons'])
M=len(neurons); N=len(I); yrep=((y7==1)&(y8==1)).astype(int); idx={n:i for i,n in enumerate(neurons)}
BM=np.hstack([base,katz,z2['MF']]); r1=z2['r1']
# per-stage chemical directed edges
stg=defaultdict(lambda: np.zeros((M,M)))
with open("../data/celegans/data/connectome/witvliet2020/witvliet_combined_edges.csv") as f:
    for r in csv.DictReader(f):
        if r['type']!='chemical': continue
        ds=int(re.search(r'witvliet_2020_(\d)',r['source_file']).group(1))
        if r['pre'] in idx and r['post'] in idx:
            s={1:'L1',2:'L1',3:'L1',4:'L1',5:'L2',6:'L3',7:'A',8:'A'}[ds]
            stg[s][idx[r['pre']],idx[r['post']]]+=r['synapses'] and 1
GL1=(stg['L1']>0).astype(float)  # L1 seed graph
# contact-allowed = the contacting directed pair set
CA=np.zeros((M,M)); CA[I,J]=1
# adult reproducible core as matrix
AD=np.zeros((M,M)); AD[I,J]=yrep
P(f"L1 seed edges={int(GL1.sum())} | adult core edges={int(AD.sum())} | contacting pairs={int(CA.sum())}")
def rewrite(seed, tau, mode, iters=25):
    G=seed.copy(); step=np.where(G>0,0,-1).astype(float)
    for t in range(1,iters+1):
        Cu=((G+G.T)>0).astype(float)
        if mode=='triadic': score=Cu@Cu           # shared undirected partners
        elif mode=='path': score=G@G              # feedforward i->k->j
        cand=(CA>0)&(G==0)&(score>=tau)&(np.eye(M)==0)
        if not cand.any(): break
        G[cand]=1; step[(step<0)&(G>0)]=t
    return G, step
# evaluate rule match to adult + hard-core FN generation
FN=(r1>0.3); FNmat=np.zeros((M,M),bool); FNmat[I[FN],J[FN]]=True
for mode in ['triadic','path']:
    for tau in [1,2,3]:
        Gs,step=rewrite(GL1,tau,mode)
        gen=np.array([step[I[k],J[k]] for k in range(N)])  # -1 never, 0 in L1 seed, >0 generated at step
        newlygen=(gen>0)
        # match to adult among contacting pairs
        pred=(Gs[I,J]>0).astype(int)
        prec=yrep[pred==1].mean() if (pred==1).any() else 0; rec=pred[yrep==1].mean()
        fn_gen=newlygen[FN].mean()  # frac of surprising-connections newly generated by rule
        base_gen=newlygen[yrep==0].mean()
        P(f"  [{mode} tau>={tau}] generated {int(newlygen.sum())} new edges | adult-match prec={prec:.2f} rec={rec:.2f} | FN(surprising-conn) rule-generated={fn_gen:.2f} vs non-core baseline {base_gen:.2f}")
# best: use generation-step as a FEATURE, does it reduce residual?
Gs,step=rewrite(GL1,2,'triadic'); gen=np.array([step[I[k],J[k]] for k in range(N)])
GEN=np.column_stack([(gen>0).astype(float),np.where(gen<0,99,gen)])
cv=StratifiedKFold(5,shuffle=True,random_state=0)
nf={n:i%5 for i,n in enumerate(sorted(set([neurons[i] for i in I]+[neurons[j] for j in J])))}
def nho(Xf,ret=False):
    pred=np.full(N,np.nan)
    for f in range(5):
        te=[k for k in range(N) if nf[neurons[I[k]]]==f and nf[neurons[J[k]]]==f];tr=[k for k in range(N) if nf[neurons[I[k]]]!=f and nf[neurons[J[k]]]!=f]
        pred[np.array(te)]=GradientBoostingClassifier(random_state=0).fit(Xf[tr],yrep[tr]).predict_proba(Xf[te])[:,1]
    m=~np.isnan(pred); return (roc_auc_score(yrep[m],pred[m]),pred) if ret else roc_auc_score(yrep[m],pred[m])
def disp(Xf):
    y2=np.concatenate([y7,y8]);X2=np.vstack([Xf,Xf]);p=np.clip(cross_val_predict(GradientBoostingClassifier(random_state=0),X2,y2,cv=cv,method='predict_proba')[:,1][:N],1e-4,1-1e-4)
    return disagree.mean()/(2*p*(1-p)).mean()
disagree=(y7!=y8).astype(int)
a0,p0=nho(BM,ret=True); a1,p1=nho(np.hstack([BM,GEN]),ret=True)
hard=np.abs(r1)>0.3; imp=(np.abs(yrep[hard]-p1[hard])<np.abs(yrep[hard]-p0[hard])-1e-6).mean()
P(f"\n[REWRITE-STEP as feature] base+katz+mirror AUC={a0:.3f} -> +rewrite-generation AUC={a1:.3f} (Δ{a1-a0:+.3f}) disp {disp(BM):.3f}->{disp(np.hstack([BM,GEN])):.3f} | hard-968 improved {imp*100:.0f}%")
